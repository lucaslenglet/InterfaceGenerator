using System.Text;

namespace InterfaceGenerator;

/// <summary>
/// One generated interface, mapped to the type implementing it.
/// </summary>
/// <param name="Lifetime">
/// The <c>ServiceLifetime</c> member name to register with, or <see langword="null"/> to defer to
/// the default the extension method was called with.
/// </param>
internal readonly record struct Registration(
    string ServiceType,
    string ImplementationType,
    string? Lifetime);

/// <summary>
/// What one annotated type contributes to the registration method: a registration, or nothing but
/// the fact that its author asked for one.
/// </summary>
/// <param name="Explicit">
/// Whether the type set a lifetime itself. Only these make a missing
/// <c>Microsoft.Extensions.DependencyInjection.Abstractions</c> worth reporting: a type that never
/// mentioned DI should not warn an assembly that never wanted it.
/// </param>
internal readonly record struct RegistrationRequest(Registration? Registration, bool Explicit);

/// <summary>
/// The assembly-level facts the registration method is shaped by.
/// </summary>
internal readonly record struct RegistrationHost(
    bool HasServiceCollection,
    string Namespace,
    string ClassName,
    string MethodName);

/// <summary>
/// Writes the <c>IServiceCollection</c> extension method that registers every generated interface.
/// </summary>
internal static class ServiceRegistrations
{
    public const string HintName = "ServiceCollectionExtensions.g.cs";

    private const string Di = "global::Microsoft.Extensions.DependencyInjection.";

    public static string Render(EquatableArray<Registration> registrations, RegistrationHost host)
    {
        StringBuilder builder = new StringBuilder()
            .AppendLine("// <auto-generated/>")
            .AppendLine("#nullable enable")
            .AppendLine()
            .Append("namespace ").AppendLine(host.Namespace)
            .AppendLine("{")
            .Append("    public static class ").AppendLine(host.ClassName)
            .AppendLine("    {")
            .AppendLine("        /// <summary>")
            .AppendLine("        /// Registers every type annotated with <c>[GenerateInterface]</c> against the")
            .AppendLine("        /// interface generated for it.")
            .AppendLine("        /// </summary>")
            .AppendLine("        /// <param name=\"defaultLifetime\">")
            .AppendLine("        /// The lifetime for types that did not set one themselves. A lifetime set on the")
            .AppendLine("        /// attribute wins over it.")
            .AppendLine("        /// </param>")
            .Append("        public static ").Append(Di).Append("IServiceCollection ")
            .Append(host.MethodName).AppendLine("(")
            .Append("            this ").Append(Di).AppendLine("IServiceCollection services,")
            .Append("            ").Append(Di).Append("ServiceLifetime defaultLifetime = ")
            .Append(Di).AppendLine("ServiceLifetime.Transient)")
            .AppendLine("        {");

        foreach (Registration registration in registrations)
        {
            // ServiceDescriptor rather than the AddTransient/AddScoped/AddSingleton trio: the
            // lifetime is a value here, not a method name, and it is the only form that takes one.
            builder
                .Append("            services.Add(new ").Append(Di).Append("ServiceDescriptor(typeof(")
                .Append(registration.ServiceType).Append("), typeof(")
                .Append(registration.ImplementationType).Append("), ")
                .Append(registration.Lifetime is { } lifetime ? Di + "ServiceLifetime." + lifetime : "defaultLifetime")
                .AppendLine("));");
        }

        return builder
            .AppendLine()
            .AppendLine("            return services;")
            .AppendLine("        }")
            .AppendLine("    }")
            .AppendLine("}")
            .ToString();
    }
}
